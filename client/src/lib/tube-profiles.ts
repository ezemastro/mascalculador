export interface TubeData {
  name: string;
  shape: "SHS" | "RHS";
  h: number; // mm (height — major axis for RHS)
  b: number; // mm (width — minor axis for RHS)
  t: number; // mm (wall thickness)
  A: number; // cm²
  Ix: number; // cm⁴
  Iy: number; // cm⁴
  rx: number; // cm
  ry: number; // cm
  Sx: number; // cm³ (elastic modulus — strong axis)
  Sy: number; // cm³ (elastic modulus — weak axis)
  Zx: number; // cm³ (plastic modulus ≈ 1.12·Sx)
  Zy: number; // cm³ (plastic modulus ≈ 1.12·Sy)
  J: number; // cm⁴ (torsional constant)
  peso: number; // kg/m
}

/**
 * Compute all geometric properties for a hollow rectangular tube (SHS or RHS).
 *
 * Formulas based on thin-walled hollow rectangle:
 *   A    = 2·t·(h + b − 2t)
 *   Ix   = [b·h³ − (b-2t)·(h-2t)³] / 12
 *   Iy   = [h·b³ − (h-2t)·(b-2t)³] / 12
 *   Sx/y = 2·Ix/y / (h/b)  (elastic modulus)
 *   Zx/y ≈ 1.12·Sx/y       (plastic modulus, HSS approximation per AISC Manual)
 *   rx   = √(Ix/A)
 *   J    = 2·t·(h-t)²·(b-t)² / (h+b-2t)  (Bredt's formula, closed section)
 *   peso = A × 0.785        (steel density 7850 kg/m³ → kg/m)
 *
 * All inputs in mm. All outputs in cm units with appropriate rounding.
 */
export function computeTubeProperties(
  h: number,
  b: number,
  t: number,
  shape: "SHS" | "RHS",
): TubeData {
  const A_mm2 = 2 * t * (h + b - 2 * t);
  const h3 = Math.pow(h, 3);
  const b3 = Math.pow(b, 3);
  const hi = h - 2 * t;
  const bi = b - 2 * t;
  const Ix_mm4 = (b * h3 - bi * Math.pow(hi, 3)) / 12;
  const Iy_mm4 = (h * b3 - hi * Math.pow(bi, 3)) / 12;

  // Convert to cm units
  const A = Math.round(A_mm2 / 10) / 10; // mm² → cm², 1 decimal
  const Ix = Math.round(Ix_mm4 / 10000); // mm⁴ → cm⁴, integer
  const Iy = Math.round(Iy_mm4 / 10000);

  const rx = Math.round(Math.sqrt(Ix / A) * 100) / 100; // cm, 2 decimals
  const ry = Math.round(Math.sqrt(Iy / A) * 100) / 100;

  const Sx = Math.round((20 * Ix) / h * 10) / 10; // cm³, 1 decimal
  const Sy = Math.round((20 * Iy) / b * 10) / 10;

  const Zx = Math.round(1.12 * Sx * 10) / 10; // cm³, 1 decimal
  const Zy = Math.round(1.12 * Sy * 10) / 10;

  const J_mm4 =
    (2 * t * Math.pow(h - t, 2) * Math.pow(b - t, 2)) / (h + b - 2 * t);
  const J = Math.round(J_mm4 / 10000 * 10) / 10; // mm⁴ → cm⁴, 1 decimal

  const peso = Math.round(A * 0.785 * 10) / 10; // kg/m, 1 decimal

  const name = `□ ${h}×${b}×${t}`;

  return {
    name,
    shape,
    h,
    b,
    t,
    A,
    Ix,
    Iy,
    rx,
    ry,
    Sx,
    Sy,
    Zx,
    Zy,
    J,
    peso,
  };
}

